def copy_style(dst_row, src_row):
    for col in "ABCDE":
        s, d = ws[f"{col}{src_row}"], ws[f"{col}{dst_row}"]
        d.font, d.border, d.alignment, d.fill, d.number_format = copy(s.font), copy(s.border), copy(s.alignment), copy(s.fill), s.number_format

# 예시는 내용 9행 + 빈 행. 우리는 10행이므로 마지막 내용 행의 서식(점선)을 한 줄 아래로 옮기고 그 자리는 일반 행 서식으로 채운다
last = FIRST + len(REQS) - 1
if last > LAST_SAMPLE:
    copy_style(last, LAST_SAMPLE)
    for r in range(LAST_SAMPLE, last):
        copy_style(r, LAST_SAMPLE - 1)

def lines(text):
    return sum(max(1, -(-len(line) // 48)) for line in text.split("\n"))   # C열 85폭 ≈ 한글 48자

